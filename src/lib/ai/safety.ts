/**
 * Защита от вставки инструкций в пользовательский ввод.
 * Текст пользователя всегда считается данными: чистится, обрезается и подаётся в явных ограничителях,
 * а системная инструкция велит не выполнять ничего из него. Формат ответов дополнительно закреплён схемой.
 */

const CONTROL_CHARS = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F-\u009F\u200B-\u200F\u202A-\u202E\u2066-\u2069]/g;

/** Служебные метки нашего формата: пользователь не должен подделывать их в своём тексте. */
const RESERVED = /---\s*CORRECTION\s*---/gi;

export function sanitizeUserText(input: string, maxLength: number): string {
  return input
    .normalize("NFC")
    .replace(CONTROL_CHARS, "")
    .replace(RESERVED, "—")
    .replace(/\r\n?/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim()
    .slice(0, maxLength);
}

/** Оборачивает недоверенный текст в тег; закрывающий тег внутри текста обезвреживается. */
export function wrapUntrusted(label: string, text: string): string {
  const safe = text.replace(new RegExp(`</?\\s*${label}\\s*>`, "gi"), "");
  return `<${label}>\n${safe}\n</${label}>`;
}

